const fs = require("fs");
const path = require("path");

const CJS_INDEX = path.join("dist", "cjs", "src", "index.js");

// tsc compiles `export * as arch from "./arch"` into an eager
// `exports.arch = tslib_1.__importStar(require("./arch"));`, so requiring the package
// root loads all 17 namespaces and their transitive dependency graphs — ~180MB RSS for
// a consumer that only wanted `constants`. ESM consumers are fine (bundlers tree-shake,
// and the package is marked sideEffects-free) but CJS consumers pay in full at runtime.
//
// ES module bindings are static by spec, so this can't be expressed in src/index.ts
// without breaking the ESM build. Instead we rewrite the emitted CJS barrel to attach
// each namespace as a self-replacing lazy getter. Public API is unchanged: same keys,
// same enumerability, same values.
const EAGER_NAMESPACE = /^exports\.([A-Za-z0-9_$]+) = tslib_1\.__importStar\(require\("(\.[^"]*)"\)\);$/gm;

const LAZY_PREAMBLE = `"use strict";
Object.defineProperty(exports, "__esModule", { value: true });
const tslib_1 = require("tslib");

// Attach a namespace as a lazy getter that replaces itself with the resolved namespace
// on first access, so subsequent reads are a plain property lookup. Generated by
// scripts/lazify-cjs-index.cjs — edit that script, not this file.
function lazy(name, load) {
  Object.defineProperty(exports, name, {
    configurable: true,
    enumerable: true,
    get() {
      const namespace = tslib_1.__importStar(load());
      Object.defineProperty(exports, name, { value: namespace, enumerable: true, configurable: true });
      return namespace;
    },
  });
}
`;

function lazifyCjsIndex() {
  if (!fs.existsSync(CJS_INDEX)) {
    console.error(`Error: ${CJS_INDEX} not found. Run the CJS build first.`);
    process.exit(1);
  }

  const source = fs.readFileSync(CJS_INDEX, "utf8");

  if (source.includes("function lazy(name, load)")) {
    console.log("CJS index already lazified, skipping");
    return;
  }

  const namespaces = [...source.matchAll(EAGER_NAMESPACE)].map(([, name, request]) => ({ name, request }));

  // Fail loudly rather than silently shipping the eager barrel: a tsc upgrade that
  // changes the emit shape must not quietly regress package-root memory usage.
  if (namespaces.length === 0) {
    console.error(
      `Error: no eager namespace re-exports found in ${CJS_INDEX}. ` +
        "The tsc emit shape has probably changed — update EAGER_NAMESPACE in this script."
    );
    process.exit(1);
  }

  const bindings = namespaces.map(({ name, request }) => `lazy("${name}", () => require("${request}"));`);

  // The rewrite renumbers every line, so the emitted source map no longer applies.
  // Drop the reference instead of shipping a map that points at the wrong lines.
  fs.writeFileSync(CJS_INDEX, `${LAZY_PREAMBLE}\n${bindings.join("\n")}\n`);
  fs.rmSync(`${CJS_INDEX}.map`, { force: true });

  console.log(`Lazified ${namespaces.length} namespace exports in ${CJS_INDEX}`);
}

lazifyCjsIndex();
